import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import vm from 'node:vm';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const path = fileURLToPath(new URL('../src/lib/offer.ts', import.meta.url));
const compiled = ts.transpileModule(readFileSync(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {}, Intl };
vm.runInNewContext(compiled, context);
const { calculateOffer, makeSummary, industries, industryGroups } = context.exports;
assert.equal(calculateOffer([], false, 'regular'), null, 'No task must produce no offer');
let quote = calculateOffer(['inbox'], false, 'none');
assert.equal(quote.low, 490);
assert.equal(quote.high, 690);
assert.equal(quote.monthly, 0);
quote = calculateOffer(['inbox', 'notes', 'documents'], false, 'light');
assert.equal(quote.low, 1090);
assert.equal(quote.high, 1790);
assert.equal(quote.monthly, 99);
quote = calculateOffer(['inbox', 'calendar', 'notes', 'documents', 'marketing'], true, 'regular');
assert.equal(quote.low, 1790);
assert.equal(quote.high, 3090);
assert.equal(quote.monthly, 179);
assert.equal(calculateOffer(['inbox', 'inbox'], false, 'none').low, 490, 'Duplicate IDs must not double-charge');
const summary = makeSummary('Friseursalons', ['inbox'], false, 'light');
assert.match(summary, /Friseursalons/);
assert.match(summary, /490/);
assert.match(summary, /99/);
assert.match(summary, /Unverbindliche Kostenschätzung/);
const labels = industryGroups.flatMap(group => group.items);
assert.equal(labels.length, 25);
for (const industry of industries) {
  assert.ok(labels.includes(industry.label), 'Every primary industry must have a calculator option');
  const estimate = calculateOffer(industry.suggested, false, 'none');
  assert.ok(estimate && estimate.low <= estimate.high);
}
console.log('Offer checks passed: empty selection, start price, multiple tasks, connections, support, duplicate IDs, summary and four industry presets.');
